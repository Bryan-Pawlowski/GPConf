    [McpServerTool]
    [Description("Posts championship standings (driver points) or confidence-cup standings (player scores) for a season. " +
                 "Reuses the exact embeds /standings and /scores show.")]
    public async Task<string> PostStandings(
        [Description("Discord channel ID to post to. Falls back to CONF_DISCORD_CHANNEL_ID if omitted.")] string? channelId,
        [Description("Season name or year")] string season,
        [Description("Race name or round to compute standings through (defaults to latest)")] string? race = null,
        [Description("League name (optional; required for confidenceCup)")] string? league = null,
        [Description("If true, posts confidence-cup player standings instead of the driver championship")] bool confidenceCup = false,
        [Description("If true, DM dmUserId instead of posting to the channel.")] bool ephemeral = false,
        [Description("Discord user ID to DM when ephemeral is true")] string? dmUserId = null)
    {
        var mainData = data.Load();
        var s = data.FindSeason(mainData, season);
        if (s is null) return $"Season '{season}' not found.";
        var target = race is null ? data.LatestRace(s) : data.FindRace(s, race);
        if (target is null) return $"Race '{race}' not found in {s.Name}.";

        Embed embed;
        if (confidenceCup)
        {
            var (_, gs) = data.FindGameSeason(mainData, s, league);
            if (gs is null) return $"No game season found for '{s.Name}'.";
            embed = ReadCommands.BuildScoresEmbed(data, s, gs, target);
        }
        else
        {
            embed = ReadCommands.BuildStandingsEmbed(data, mainData, s, target, league);
        }
        return await SendAsync(channelId, ephemeral, dmUserId, embed);
    }

    [McpServerTool]
    [Description("Generates narrative content via the local Ollama model from facts the caller has already " +
                 "researched, and posts it as a Discord embed with one field per section. The model only " +
                 "narrates factsMarkdown — it never invents facts, same anti-hallucination contract as the " +
                 "/driver-analysis-style slash commands. Call this once per genuinely new piece of narrative " +
                 "content. If a later step needs to display content that's already been generated (by this " +
                 "tool or by the caller itself), do NOT call this again — format it as markdown and use " +
                 "post_message instead.")]
    public async Task<string> GenerateAndPost(
        [Description("Discord channel ID to post to. Falls back to CONF_DISCORD_CHANNEL_ID if omitted.")] string? channelId,
        [Description("Embed title")] string title,
        [Description("Real facts already researched by the caller — the model narrates only these, never " +
                     "inventing names/numbers/events not listed here.")] string factsMarkdown,
        [Description("Comma-separated section labels the model must use, in order, e.g. " +
                     "'Track & History, Storylines Since Last Race, What To Watch'. Include your own emoji in " +
                     "a label if you want one, e.g. '🏎️ Track & History'.")] string sections,
        [Description("Extra tone/style guidance appended to the base system prompt, e.g. 'race-weekend " +
                     "preview, speculative and upbeat about who could succeed or struggle' or 'grounded " +
                     "post-race recap, backed only by the facts given'.")] string? styleGuidance = null,
        [Description("Optional accent color as a hex string, e.g. '1E90FF'")] string? colorHex = null,
        [Description("If true, DM dmUserId instead of posting to the channel.")] bool ephemeral = false,
        [Description("Discord user ID to DM when ephemeral is true")] string? dmUserId = null)
    {
        var sectionLabels = sections.Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);
        if (sectionLabels.Length == 0) return "sections must list at least one section label.";

        var systemPrompt = BaseSystemPrompt + (string.IsNullOrWhiteSpace(styleGuidance) ? "" : $"\n\nStyle guidance: {styleGuidance}");
        var userPrompt = $"{factsMarkdown}\n\nStructure your response into these sections, in this order: {string.Join(", ", sectionLabels)}.";

        string text;
        try { text = await ollama.GenerateAsync(systemPrompt, userPrompt); }
        catch (OllamaException ex) { return $"Couldn't generate content: {ex.Message}"; }

        var builder = new EmbedBuilder().WithTitle(title).WithColor(ParseColor(colorHex));
        var parsed = AnalysisCommands.ParseSections(text);
        if (parsed.Count > 0)
        {
            foreach (var label in sectionLabels)
            {
                if (!parsed.TryGetValue(label, out var body) || body.Length == 0) continue;
                if (body.Length > AnalysisCommands.MaxFieldLength) body = body[..AnalysisCommands.MaxFieldLength] + "…";
                builder.AddField(label, body);
            }
        }
        else
        {
            // Model ignored the section format — fall back to a plain description so nothing breaks.
            builder.WithDescription(text.Length > AnalysisCommands.MaxDescriptionLength ? text[..AnalysisCommands.MaxDescriptionLength] + "…" : text);
        }

        return await SendAsync(channelId, ephemeral, dmUserId, builder.Build());
    }

    // Resolves either a channel (normal path) or a DM channel to dmUserId (ephemeral path) via
    // REST, not the gateway cache — the bot runs with GatewayIntents.None (it only ever handles
    // slash-command interactions, which carry their own channel/guild context), so the socket
    // cache never gets populated with guild/channel data. REST lookups work regardless.
    private async Task<string> SendAsync(string? channelId, bool ephemeral, string? dmUserId, Embed embed,
        MessageComponent? components = null, bool mentionHere = false)
    {
        var sent = await SendAsyncCore(channelId, ephemeral, dmUserId, embed, components, mentionHere);
        if (sent is null) return $"Couldn't resolve the target channel/user for {channelId ?? dmUserId}.";
        return ephemeral ? $"DMed {dmUserId}." : $"Posted to channel {sent.Channel.Id}.";
    }

    // Like SendAsync but returns the sent message (null on resolution failure) so callers that
    // need to later edit/delete it can capture its ID.
    private async Task<IUserMessage?> SendAsyncCore(string? channelId, bool ephemeral, string? dmUserId, Embed embed,
        MessageComponent? components = null, bool mentionHere = false)
    {
        IMessageChannel? channel;
        if (ephemeral)
        {
            if (dmUserId is null || !ulong.TryParse(dmUserId, out var uid))
                return null;
            var user = await client.Rest.GetUserAsync(uid);
            if (user is null) return null;
            channel = await user.CreateDMChannelAsync();
        }
        else
        {
            // Default target for every race-week automation skill: #race-week (guild 151923917966016514).
            // CONF_DISCORD_CHANNEL_ID overrides this; an explicit channelId argument overrides both.
            var idStr = channelId ?? Environment.GetEnvironmentVariable("CONF_DISCORD_CHANNEL_ID") ?? DefaultChannelId;
            if (!ulong.TryParse(idStr, out var id))
                return null;
            channel = await client.Rest.GetChannelAsync(id) as IMessageChannel;
            if (channel is null) return null;
        }

        var allowedMentions = mentionHere ? new AllowedMentions(AllowedMentionTypes.Everyone) : null;
        return await channel.SendMessageAsync(mentionHere ? "@here" : null, embed: embed, components: components, allowedMentions: allowedMentions);
    }

    private static Color ParseColor(string? hex)
    {
        if (string.IsNullOrWhiteSpace(hex)) return Color.Blue;
        var cleaned = hex.TrimStart('#');
        return uint.TryParse(cleaned, NumberStyles.HexNumber, CultureInfo.InvariantCulture, out var packed)
            ? new Color((byte)((packed >> 16) & 0xFF), (byte)((packed >> 8) & 0xFF), (byte)(packed & 0xFF))
            : Color.Blue;
    }
